import re

from rdkit import Chem

from app.schemas.calculation import OrcaInputRequest, OrcaInputResponse
from app.services.chemistry.errors import ChemistryError


TASK_KEYWORDS = {
    "single_point": "SP",
    "optimization": "Opt",
    "frequency": "Freq",
    "opt_freq": "Opt Freq",
}


def safe_filename(name: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9_-]+", "_", name).strip("_")
    return normalized or "molecule"


def generate_orca_input(request: OrcaInputRequest) -> OrcaInputResponse:
    molecule = Chem.MolFromMolBlock(request.mol_block, removeHs=False, sanitize=True)
    if molecule is None or molecule.GetNumAtoms() == 0:
        raise ChemistryError("invalid_mol_block", "A valid molecular structure is required.", 422)
    if molecule.GetNumConformers() == 0 or not molecule.GetConformer().Is3D():
        raise ChemistryError("missing_3d_coordinates", "ORCA input requires three-dimensional coordinates.", 422)

    conformer = molecule.GetConformer()
    coordinates = []
    for atom in molecule.GetAtoms():
        position = conformer.GetAtomPosition(atom.GetIdx())
        coordinates.append(
            f"  {atom.GetSymbol():<3} {position.x:>16.10f} {position.y:>16.10f} {position.z:>16.10f}"
        )

    lines = [
        f"# {request.name} | generated by Organic Molecular Workbench",
        "# Input file only: no ORCA calculation has been executed.",
        f"! {request.functional} {request.basis_set} {TASK_KEYWORDS[request.task]} TightSCF",
        "",
        f"%pal nprocs {request.nprocs} end",
        f"%maxcore {request.maxcore_mb}",
        "",
        f"* xyz {request.charge} {request.multiplicity}",
        *coordinates,
        "*",
        "",
    ]
    return OrcaInputResponse(
        input_text="\n".join(lines),
        filename=f"{safe_filename(request.name)}_{request.task}.inp",
    )
